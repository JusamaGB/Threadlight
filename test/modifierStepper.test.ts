import { afterEach, describe, expect, it, vi } from 'vitest'
import { ModifierStepper } from '../src/main/modifierStepper'

afterEach(() => vi.useRealTimers())
describe('modifier hold stepper', () => {
  it('steps through Control, Control+Alt, either release order, pause and disposal', () => {
    vi.useFakeTimers()
    const down = new Set<number>()
    const change = vi.fn()
    const stepper = new ModifierStepper(change, (key) => down.has(key))
    stepper.start()
    const tick = () => vi.advanceTimersByTime(25)
    down.add(0x11)
    tick()
    expect(change).toHaveBeenLastCalledWith('hidden')
    down.add(0x12)
    tick()
    expect(change).toHaveBeenLastCalledWith('peek')
    const count = change.mock.calls.length
    tick()
    expect(change).toHaveBeenCalledTimes(count)
    down.delete(0x12)
    tick()
    expect(change).toHaveBeenLastCalledWith('hidden')
    down.delete(0x11)
    tick()
    expect(change).toHaveBeenLastCalledWith('normal')
    down.add(0x12)
    tick()
    expect(change).toHaveBeenCalledTimes(count + 2)
    down.add(0x11)
    tick()
    expect(change).toHaveBeenLastCalledWith('peek')
    down.delete(0x11)
    tick()
    expect(change).toHaveBeenLastCalledWith('normal')
    down.add(0x11)
    tick()
    stepper.setPaused(true)
    expect(change).toHaveBeenLastCalledWith('normal')
    stepper.setPaused(false)
    expect(change).toHaveBeenLastCalledWith('peek')
    stepper.dispose()
    expect(change).toHaveBeenLastCalledWith('normal')
    const final = change.mock.calls.length
    tick()
    expect(change).toHaveBeenCalledTimes(final)
  })
  it('stays normal when key state is unavailable', () => {
    vi.useFakeTimers()
    const change = vi.fn()
    const stepper = new ModifierStepper(change, () => null)
    stepper.start()
    vi.advanceTimersByTime(100)
    stepper.dispose()
    expect(change).not.toHaveBeenCalled()
  })
  it('yields to the talk shortcut until Control is released, then accepts another hold', () => {
    vi.useFakeTimers()
    const down = new Set([0x11, 0x12])
    const change = vi.fn()
    const stepper = new ModifierStepper(change, (key) => down.has(key))
    stepper.start()
    expect(change).toHaveBeenLastCalledWith('peek')
    stepper.yieldToTalk()
    expect(change).toHaveBeenLastCalledWith('normal')
    const count = change.mock.calls.length
    vi.advanceTimersByTime(100)
    expect(change).toHaveBeenCalledTimes(count)
    down.clear()
    vi.advanceTimersByTime(25)
    down.add(0x11)
    vi.advanceTimersByTime(25)
    expect(change).toHaveBeenLastCalledWith('hidden')
    stepper.dispose()
  })
})
