// One canonical bridge, skill and protocol; committed copies make plugin caches standalone.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const formatting = await resolveConfig(resolve(root, 'scripts/memory-protocol.json'))
const require = createRequire(import.meta.url),
  ts = require('typescript')
require.extensions['.ts'] = (module, filename) =>
  module._compile(
    ts.transpileModule(readFileSync(filename, 'utf8'), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    }).outputText,
    filename,
  )
const { browserTools, BROWSER_INSTRUCTIONS } = require('../src/shared/browser.ts')
const { memoryTools, memoryInstructions } = require('../src/main/memory/protocol.ts')
const { communicationTools, communicationInstructions } = require('../src/shared/communication.ts')
const setupSkill = readFileSync(resolve(root, 'skills/setup/SKILL.md'), 'utf8').replaceAll(
  '\r\n',
  '\n',
)
const browserGuide = readFileSync(resolve(root, 'docs/FEATURES.md'), 'utf8')
  .replaceAll('\r\n', '\n')
  .split('## Shared browser\n')[1]
  ?.split('\n## ')[0]
if (!browserGuide) throw new Error('Missing shared browser guide in docs/FEATURES.md')
const packagedBrowserGuide =
  '# Shared browser\n\n<!-- Generated from docs/FEATURES.md by scripts/package-memory-plugins.mjs. -->\n' +
  browserGuide.replace(
    '[browser validation](validation/SHARED-BROWSER.md)',
    '`docs/validation/SHARED-BROWSER.md` in the source checkout',
  )
const generated = new Map([
  ['skills/shared-memory/references/browser.md', packagedBrowserGuide],
  ['codex-plugin/skills/shared-memory/references/browser.md', packagedBrowserGuide],
  ['codex-plugin/skills/setup/SKILL.md', setupSkill],
  [
    'perplexity-skill/threadlight-setup/SKILL.md',
    setupSkill.replace('name: setup\n', 'name: threadlight-setup\n'),
  ],
  [
    'codex-plugin/scripts/memory-pairings.mjs',
    readFileSync(resolve(root, 'scripts/memory-pairings.mjs'), 'utf8'),
  ],
  [
    'src/main/memory/proxySource.ts',
    await format(
      '// Generated by scripts/package-memory-plugins.mjs.\nexport default ' +
        JSON.stringify(readFileSync(resolve(root, 'scripts/memory-transport.mjs'), 'utf8')) +
        '\n',
      { ...formatting, parser: 'typescript' },
    ),
  ],
  [
    'codex-plugin/scripts/memory-transport.mjs',
    readFileSync(resolve(root, 'scripts/memory-transport.mjs'), 'utf8'),
  ],
  [
    'codex-plugin/scripts/hook-client.mjs',
    readFileSync(resolve(root, 'scripts/hook-client.mjs'), 'utf8'),
  ],
  [
    'scripts/memory-protocol.json',
    await format(
      JSON.stringify({
        version: 1,
        instructions: `${memoryInstructions}\n${communicationInstructions}\n${BROWSER_INSTRUCTIONS}`,
        tools: [...memoryTools, ...communicationTools, ...browserTools],
      }),
      { ...formatting, parser: 'json' },
    ),
  ],
  [
    'codex-plugin/scripts/memory-protocol.json',
    await format(
      JSON.stringify({
        version: 1,
        instructions: `${memoryInstructions}\n${communicationInstructions}\n${BROWSER_INSTRUCTIONS}`,
        tools: [...memoryTools, ...communicationTools, ...browserTools],
      }),
      { ...formatting, parser: 'json' },
    ),
  ],
  [
    'codex-plugin/scripts/memory-bridge.mjs',
    readFileSync(resolve(root, 'scripts/memory-bridge.mjs'), 'utf8'),
  ],
  [
    'codex-plugin/skills/shared-memory/SKILL.md',
    readFileSync(resolve(root, 'skills/shared-memory/SKILL.md'), 'utf8'),
  ],
])
for (const [file, content] of generated) {
  const path = resolve(root, file)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n'))
      throw new Error(`Stale plugin asset: ${file}. Run npm run plugins:package.`)
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Plugin assets match canonical sources.'
    : 'Packaged both memory plugins.',
)
